def check_new_password(password: str, email: str) -> str | None:
    """Why ``password`` can't be used for the account with ``email``, or None if it can."""

    if not password.strip():
        return "A password can't be only spaces"
    normalized = password.strip().lower()
    if normalized == email.strip().lower():
        return "Pick a password that isn't your email"
    if normalized in COMMON_PASSWORDS:
        return "That password is too common. Pick one that's harder to guess"
    return None
